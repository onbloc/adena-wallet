#!/usr/bin/env node
/**
 * Builds the page-side provider that the in-app browser injects: the
 * extension's own inject.ts (window.adena, AdenaExecutor), unchanged, so dApps
 * see the same API on mobile as in the extension. Output is a JS module that
 * exports the bundle as a string; it is generated, not committed.
 */
const {build} = require('esbuild');
const {writeFileSync, mkdirSync} = require('fs');
const path = require('path');

const extensionRoot = path.resolve(__dirname, '../../adena-extension');
const moduleEntry = path.resolve(__dirname, '../../adena-module/index.ts');
const emptyModule = path.resolve(__dirname, '../src/platform/stubs/node-crypto-empty.js');

// Node's crypto is optional in these libraries (they fall back to Web Crypto).
const nodeBuiltins = {
  name: 'node-builtins',
  setup(pluginBuild) {
    pluginBuild.onResolve({filter: /^(crypto|vm)$/}, () => ({path: emptyModule}));
    pluginBuild.onResolve({filter: /^adena-module$/}, () => ({path: moduleEntry}));
  },
};
const outFile = path.resolve(__dirname, '../src/browser/provider/generated/provider-bundle.js');

build({
  entryPoints: [path.join(extensionRoot, 'src/inject.ts')],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: 'es2019',
  minify: true,
  legalComments: 'none',
  tsconfig: path.join(extensionRoot, 'tsconfig.json'),
  define: {'process.env.NODE_ENV': '"production"', global: 'globalThis'},
  inject: [path.join(__dirname, 'provider-node-shims.js')],
  plugins: [nodeBuiltins],
  logLevel: 'warning',
})
  .then(result => {
    const code = result.outputFiles[0].text;
    mkdirSync(path.dirname(outFile), {recursive: true});
    writeFileSync(
      outFile,
      `// Generated by scripts/build-provider.js. Do not edit.\nmodule.exports = ${JSON.stringify(code)};\n`,
    );
    console.log(`provider bundle: ${(code.length / 1024).toFixed(0)} KiB`);
  })
  .catch(error => {
    console.error(error);
    process.exit(1);
  });
