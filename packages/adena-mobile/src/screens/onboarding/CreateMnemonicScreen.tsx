import {ADENA_DOCS_PAGE} from '@common/constants/resource.constant';
import type {NativeStackScreenProps} from '@react-navigation/native-stack';
import {AdenaWallet} from 'adena-module';
import React, {useEffect, useState} from 'react';
import {StyleSheet, View} from 'react-native';

import {pendingSecret} from '../../core/pending-secret';
import type {OnboardingStackParams} from '../../navigation/types';
import {
  copyWithExpiry,
  SECRET_CLIPBOARD_CLEAR_MS,
} from '../../security/sensitive-clipboard';
import {useSecureScreen} from '../../security/use-secure-screen';
import {
  HoldToReveal,
  SeedGrid,
  WebButton,
  WebCheckBox,
  WebCopyButton,
  WebDanger,
  WebHoldButton,
  WebScreen,
  WebStepHeader,
  WebTabs,
  WebTitle,
  WebWarning,
} from '../../ui/web';
import {Questionnaire} from './Questionnaire';
import {SensitiveInfoStep} from './SensitiveInfoStep';

type Props = NativeStackScreenProps<OnboardingStackParams, 'CreateMnemonic'>;

type WordCount = 12 | 24;

export const COPIED_WARNING =
  'You have copied sensitive info. Do not paste it in public or shared places. The clipboard is cleared in 30 seconds.';

const WORD_COUNT_TABS: {key: `${WordCount}`; label: string}[] = [
  {key: '12', label: '12 words'},
  {key: '24', label: '24 words'},
];

/**
 * Create flow: this screen (warning, questionnaire, phrase), ConfirmMnemonic,
 * SetPassword.
 */
export const CREATE_FLOW_STEPS = 5;

/** Generated by the native CSPRNG (via CryptoProvider). */
function generateWords(count: WordCount): string[] {
  const mnemonic = AdenaWallet.generateMnemonic(count);
  pendingSecret.set({kind: 'mnemonic', value: mnemonic});
  return mnemonic.split(' ');
}

/**
 * The extension's create-wallet steps: a warning, the security
 * questionnaire, then the phrase (12 or 24 words), masked until the user
 * agrees and holds the reveal button. Copy is there as on the web, with a
 * warning, and the clipboard is cleared after 30 seconds.
 */
export function CreateMnemonicScreen({navigation}: Props) {
  const {screenshotTaken} = useSecureScreen();
  const [phase, setPhase] = useState<'intro' | 'questionnaire' | 'phrase'>(
    'intro',
  );
  const [wordCount, setWordCount] = useState<WordCount>(24);
  const [words, setWords] = useState<string[]>([]);
  const [agreed, setAgreed] = useState(false);
  // Shown at least once: from then on the main button is Next.
  const [seen, setSeen] = useState(false);
  const [revealed, setRevealed] = useState(false);
  const [saved, setSaved] = useState(false);
  const [copied, setCopied] = useState(false);

  useEffect(() => () => setWords([]), []);

  const changeWordCount = (count: WordCount) => {
    if (count === wordCount) {
      return;
    }
    setWordCount(count);
    setWords(generateWords(count));
    setSeen(false);
    setRevealed(false);
    setSaved(false);
  };

  const leave = () => {
    pendingSecret.clear();
    navigation.goBack();
  };

  const header = (step: number, onBack: () => void) => (
    <WebStepHeader step={step} steps={CREATE_FLOW_STEPS} onBack={onBack} />
  );

  if (phase === 'intro') {
    return (
      <WebScreen header={header(0, leave)}>
        <SensitiveInfoStep
          description="This will generate a seed phrase on your device. Only proceed if you understand how to safely store your seed phrase."
          learnMoreUrl={`${ADENA_DOCS_PAGE}/user-guide/sign-in/create-new-wallet`}
          onNext={() => setPhase('questionnaire')}
        />
      </WebScreen>
    );
  }

  if (phase === 'questionnaire') {
    return (
      <Questionnaire
        header={onBack => header(1, onBack)}
        onExit={() => setPhase('intro')}
        onComplete={() => {
          setWords(generateWords(wordCount));
          setPhase('phrase');
        }}
      />
    );
  }

  return (
    <WebScreen
      header={header(2, () => {
        pendingSecret.clear();
        setWords([]);
        setSeen(false);
        setRevealed(false);
        setSaved(false);
        setPhase('intro');
      })}
      footer={
        seen ? (
          <WebButton
            testID="mnemonic-next"
            title="Next"
            chevron
            disabled={!saved}
            onPress={() => {
              setRevealed(false);
              navigation.navigate('ConfirmMnemonic');
            }}
          />
        ) : (
          <WebHoldButton
            testID="mnemonic-reveal"
            title="Hold to Reveal Seed Phrase"
            disabled={!agreed}
            onComplete={() => {
              setSeen(true);
              setRevealed(true);
            }}
          />
        )
      }>
      <View style={styles.messages}>
        <WebTitle title="Seed Phrase" />
        <WebWarning>
          This phrase is the only way to recover this wallet. DO NOT share it
          with anyone.
        </WebWarning>
        {screenshotTaken ? (
          <WebDanger>
            A screenshot was taken. Delete it from your photos and any cloud
            backup: apps that read your gallery can steal the phrase. Consider
            creating a new wallet.
          </WebDanger>
        ) : (
          <WebWarning>
            Write it on paper. Do not take a screenshot or keep it in a notes or
            cloud app.
          </WebWarning>
        )}
        {copied && <WebWarning>{COPIED_WARNING}</WebWarning>}
      </View>
      <WebTabs
        tabs={WORD_COUNT_TABS}
        value={`${wordCount}`}
        onChange={key => changeWordCount(Number(key) as WordCount)}
      />
      <SeedGrid words={words} hidden={!revealed} />
      {seen ? (
        <>
          <View style={styles.actions}>
            <HoldToReveal revealed={revealed} onChange={setRevealed} />
            <WebCopyButton
              testID="mnemonic-copy"
              onCopy={() => {
                copyWithExpiry(words.join(' '), SECRET_CLIPBOARD_CLEAR_MS);
                setCopied(true);
              }}
            />
          </View>
          <WebCheckBox
            testID="mnemonic-saved"
            checked={saved}
            onChange={setSaved}
            label="I have saved my seed phrase."
          />
        </>
      ) : (
        <WebCheckBox
          testID="mnemonic-agree"
          checked={agreed}
          onChange={setAgreed}
          label="This phrase will only be stored on this device. Adena can't recover it for you."
        />
      )}
    </WebScreen>
  );
}

const styles = StyleSheet.create({
  messages: {gap: 16},
  actions: {flexDirection: 'row', justifyContent: 'center', gap: 12},
});
